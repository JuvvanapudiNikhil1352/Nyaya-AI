/**
 * Deterministic safety screening of user messages.
 *
 * Runs on every message IN ADDITION to the AI's own judgement, so safety
 * guidance appears even if the AI misses it or is unavailable. It is
 * deliberately broad: a false alarm only shows a help banner; a miss could
 * leave someone in danger without guidance.
 */

const THREAT_PATTERNS: RegExp[] = [
  /\bthreat(en|ened|ening|ens|s)?\b/i,
  /\b(kill|murder|stab|shoot)\b/i,
  /\b(beat|beating|beaten|hit|hitting|slap|slapped|attack|attacked|assault(ed)?)\b/i,
  /\bbreak (my|your|his|her|our) (legs?|arms?|hands?|bones?|head)\b/i,
  /\b(goons?|rowdies|rowdy|henchmen|thugs?)\b/i,
  /\b(harass(ed|ing|ment)?|abus(e|ed|ing|ive)|intimidat(e|ed|ing|ion))\b/i,
  /\b(kidnap|abduct)(ped|ed|ing)?\b/i,
  /\b(blackmail(ed|ing)?|extort(ed|ion)?)\b/i,
  /\b(came|come|coming|sent .{0,20}) to (my|our) (house|home|shop|office|workplace)\b/i,
  /\b(follow(ed|ing) me|stalk(ed|ing)?)\b/i,
  // Persistent pressure: repeated calls or messages, pressuring to pay.
  /\b(repeatedly|constantly|continuously|keeps?|kept|again and again)\s+(calling|phoning|messaging|texting|coming)\b/i,
  /\bpressur(e|es|ed|ing)\s+(me|us|my family)\b/i,
  /\b(seiz(e|ed)|took|take|grab(bed)?) (my|our) (house|land|property|gold|vehicle|bike|documents?)\b/i,
  /\b(unsafe|in danger|scared for my (life|family|safety))\b/i,
  /\b(morph(ed)?|obscene|nude|private) (photos?|pictures?|images?|videos?)\b/i,
];

const SELF_HARM_PATTERNS: RegExp[] = [
  /\b(suicide|suicidal)\b/i,
  /\b(kill|hurt|harm) (myself|ourselves)\b/i,
  /\b(end|ends|ending|ended|take|taking) (my|our) (own )?li(fe|ves)\b/i,
  /\bend (it|everything) all\b/i,
  /\b(want|wanted|wish) to die\b/i,
  /\b(no reason|nothing left|no point) (to live|in living|living)\b/i,
  /\b(consum(e|ed)|drink|drank|took) (poison|pesticide)\b/i,
];

export type SafetyScreen = { concern: boolean; selfHarm: boolean };

export function screenMessage(text: string): SafetyScreen {
  const selfHarm = SELF_HARM_PATTERNS.some((p) => p.test(text));
  const concern = selfHarm || THREAT_PATTERNS.some((p) => p.test(text));
  return { concern, selfHarm };
}

/**
 * Removes identifiers the app never needs (minimal data collection) BEFORE the
 * message is stored or sent to any AI provider.
 */
const SENSITIVE_PATTERNS: [RegExp, string][] = [
  // Secrets after a keyword: "PIN is 4321", "otp: 123456", "password - abc"
  [/\b(upi\s*pin|m-?pin|pin|otp|password|passcode|cvv)\b(\s*(is|was|:|-|=)?\s*)[^\s,.;]+/gi, "$1$2[removed]"],
  // Card numbers first (13–19 digits, optionally grouped), so a 16-digit card
  // isn't half-matched by the Aadhaar pattern below.
  [/\b(?:\d[ -]?){12,18}\d\b/g, "[removed]"],
  // Aadhaar: 12 digits, optionally grouped 4-4-4
  [/\b\d{4}[\s-]?\d{4}[\s-]?\d{4}\b/g, "[removed]"],
  // PAN: AAAAA9999A
  [/\b[A-Z]{5}\d{4}[A-Z]\b/g, "[removed]"],
  // Bank account numbers (9–18 plain digits)
  [/\b\d{9,18}\b/g, "[removed]"],
];

export function redactSensitive(text: string): { text: string; redacted: boolean } {
  let out = text;
  for (const [pattern, replacement] of SENSITIVE_PATTERNS) out = out.replace(pattern, replacement);
  return { text: out, redacted: out !== text };
}

